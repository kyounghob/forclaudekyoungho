def _balanced() -> dict:
    """단원 순서대로 보기를 0·1·2·3칸씩 돌려 정답 위치를 고르게 나눈다."""
    out = {}
    for n, (key, (text, options, explain)) in enumerate(sorted(_RAW.items(), key=lambda kv: (kv[0][0], kv[0][1]))):
        shift = n % len(options)
        opts = options[-shift:] + options[:-shift] if shift else list(options)
        out[key] = dict(text=text, options=opts, answer=opts.index(options[0]), explain=explain)
    return out


UNIT_CHECKS = _balanced()


def unit_check(topic: str, level: int):
    """(주제, 수준) 단원의 이해 확인 문항(text·options·answer·explain) 사본. 없으면 None."""
    q = UNIT_CHECKS.get((topic, int(level)))
